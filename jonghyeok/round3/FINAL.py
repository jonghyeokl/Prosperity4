def _norm_cdf(x):
    return 0.5 * (1.0 + math.erf(x / math.sqrt(2.0)))


def _norm_pdf(x):
    return math.exp(-0.5 * x * x) / math.sqrt(2.0 * math.pi)


def bs_call_with_greeks(S, K, T, sigma):
    if S <= 0 or K <= 0 or T <= 0 or sigma <= 0:
        return max(S - K, 0.0), (1.0 if S > K else 0.0), 0.0

    sqrtT = math.sqrt(T)
    d1 = (math.log(S / K) + 0.5 * sigma * sigma * T) / (sigma * sqrtT)
    d2 = d1 - sigma * sqrtT

    price = S * _norm_cdf(d1) - K * _norm_cdf(d2)
    delta = _norm_cdf(d1)
    vega = S * _norm_pdf(d1) * sqrtT

    return price, delta, vega


def implied_vol(V, S, K, T, tol=1e-4, max_iter=50):
    """Bisection IV. Returns None if no solution in range."""
    if T <= 0 or V <= 0 or S <= 0 or K <= 0:
        return None

    intrinsic = max(S - K, 0.0)

    if V < intrinsic - 1e-2 or V > S + 1e-2:
        return None

    lo, hi = 1e-3, 3.0

    f_lo = bs_call_with_greeks(S, K, T, lo)[0] - V
    f_hi = bs_call_with_greeks(S, K, T, hi)[0] - V

    if f_lo * f_hi > 0:
        return None

    for _ in range(max_iter):
        mid = 0.5 * (lo + hi)
        f_mid = bs_call_with_greeks(S, K, T, mid)[0] - V

        if abs(f_mid) < tol:
            return mid

        if f_lo * f_mid < 0:
            hi, f_hi = mid, f_mid
        else:
            lo, f_lo = mid, f_mid

    return 0.5 * (lo + hi)


def fit_quadratic_from_points(points: List[Tuple[float, float]]) -> Optional[Tuple[float, float, float]]:
    """OLS fit iv = a*m^2 + b*m + c. Returns None on singular."""
    n = len(points)

    if n < 4:
        return None

    Sx4 = Sx3 = Sx2 = Sx1 = 0.0
    Sy = Syx = Syx2 = 0.0

    for m, v in points:
        m2 = m * m
        Sx4 += m2 * m2
        Sx3 += m2 * m
        Sx2 += m2
        Sx1 += m
        Sy += v
        Syx += v * m
        Syx2 += v * m2

    # 3x3 normal equations
    M = [
        [Sx4, Sx3, Sx2, Syx2],
        [Sx3, Sx2, Sx1, Syx],
        [Sx2, Sx1, float(n), Sy],
    ]

    try:
        for i in range(3):
            pivot = M[i][i]

            if abs(pivot) < 1e-15:
                swap = None
                for k in range(i + 1, 3):
                    if abs(M[k][i]) > 1e-15:
                        swap = k
                        break

                if swap is None:
                    return None

                M[i], M[swap] = M[swap], M[i]
                pivot = M[i][i]

            for j in range(i + 1, 3):
                factor = M[j][i] / pivot
                for c in range(i, 4):
                    M[j][c] -= factor * M[i][c]

        x = [0.0, 0.0, 0.0]

        for i in range(2, -1, -1):
            x[i] = M[i][3]
            for j in range(i + 1, 3):
                x[i] -= M[i][j] * x[j]
            x[i] /= M[i][i]

        return x[0], x[1], x[2]

    except Exception:
        return None


